TEST(MVSFormerPlusPlus, InferenceContract) {
  MVSFormerPlusPlus::Options options;
  options.model_path = WriteMockModel().string();
  options.use_gpu = false;
  MVSFormerPlusPlus estimator(options, -1);
  EXPECT_TRUE(estimator.GetCapabilities().supports_repeated_source_images);

  constexpr float K[9] = {50, 0, 32, 0, 50, 32, 0, 0, 1};
  constexpr float R[9] = {1, 0, 0, 0, 1, 0, 0, 0, 1};
  constexpr float T[3] = {0, 0, 0};
  std::vector<Image> images;
  for (int i = 0; i < 5; ++i) {
    Image image("", 64, 64, K, R, T);
    Bitmap bitmap(64, 64, true);
    bitmap.Fill(BitmapColor<uint8_t>(128, 128, 128));
    image.SetBitmap(std::move(bitmap));
    images.push_back(std::move(image));
  }
  MVSEstimator::Problem problem;
  problem.ref_image_idx = 0;
  problem.src_image_idxs = {1, 2, 3, 4};
  problem.images = &images;
  problem.depth_min = 1.0f;
  problem.depth_max = 3.0f;
  const MVSEstimator::Result result =
      estimator.Estimate(problem, MVSEstimator::Pass::PHOTOMETRIC);
  EXPECT_EQ(result.depth_map.GetWidth(), 64);
  EXPECT_EQ(result.depth_map.GetHeight(), 64);
  EXPECT_FLOAT_EQ(result.depth_map.Get(32, 32), 2.0f);
  ASSERT_TRUE(result.confidence_map.has_value());
  EXPECT_FLOAT_EQ(result.confidence_map->Get(32, 32), 1.0f);
  EXPECT_NEAR(result.normal_map.Get(32, 32, 2), -1.0f, 1e-5f);
}

